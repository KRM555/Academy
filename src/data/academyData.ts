// Helper to format current time in an IANA timezone dynamically accounting for DST
export function formatTimezoneClock(ianaZone: string): string {
  try {
    return new Intl.DateTimeFormat('ar-SA', {
      timeZone: ianaZone,
      hour: '2-digit',
      minute: '2-digit',
      hour12: true,
    }).format(new Date());
  } catch {
    return '';
  }
}

